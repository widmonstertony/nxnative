#!/usr/bin/env python3
"""Generate a multi-game profile shim from the exact profiles used by builds.

Usage: runtime_profiles.py OUT_DIR PROFILE_DIR [PROFILE_DIR ...]
The output is build-specific and must be compiled with the host. No game data,
signing material, or shader cache is read or copied here.
"""
import re
import sys
from pathlib import Path

from game import Game, header

FIELDS = {
    'ID': ('id', 'const char *'), 'NAME': ('name', 'const char *'),
    'PROGRAM_ID': ('program_id', 'uint64_t'),
    'ROMFS_MARKER': ('romfs_marker', 'const char *'),
    'MEM_RESERVE': ('mem_reserve', 'uint64_t'), 'MEM_ALIAS': ('mem_alias', 'uint64_t'),
    'MEM_STACK': ('mem_stack', 'uint64_t'), 'APP_POOL': ('app_pool', 'uint64_t'),
    'MEM_USED': ('mem_used', 'uint64_t'), 'SYS_RESOURCE': ('sys_resource', 'uint64_t'),
    'ARGS': ('args', 'const char *'), 'ENV': ('env', 'const char *'),
    'MEM_MAP_LIMIT': ('mem_map_limit', 'int'),
    'STDALLOC_CAP': ('stdalloc_cap', 'uint64_t'),
    'PRESENT_DISPLAY': ('present_display', 'int'),
    'CORE_PREEMPT': ('core_preempt', 'int'),
    'ALLOC_BIG_ALIGN': ('alloc_big_align', 'int'),
    'FPS_TARGET': ('fps_target', 'int'), 'FPS_HOLD': ('fps_hold', 'int'),
    'PRESENT_SNAP': ('present_snap', 'int'), 'PSO_MTL4': ('pso_mtl4', 'int'),
    'PAD_LAYOUT': ('pad_layout', 'int'), 'OPMODE': ('opmode', 'int'),
    'PERF_BOOST': ('perf_boost', 'int'),
    'FEEDBACK_SNAP': ('feedback_snap', 'const char *'),
    'TEX_FLUSH_UPLOAD': ('tex_flush_upload', 'int'),
    'RENDER_COND': ('render_cond', 'int'),
    'TEX_DIRTY_UPLOAD': ('tex_dirty_upload', 'int'),
    'TEX_DYN_SLOTS': ('tex_dyn_slots', 'int'),
    'GPU_TS_SEGMENT': ('gpu_ts_segment', 'int'),
    'VCONV_RANGE': ('vconv_range', 'int'),
}


def constants(profile):
    return dict(re.findall(r'^#define DM_GAME_([A-Z0-9_]+) (.+)$', header(profile), re.M))


def generate(out, profiles):
    if not profiles or len({p.id.upper() for p in profiles}) != len(profiles):
        raise ValueError('need distinct game profiles')
    head = ['// Generated by dm/games/runtime_profiles.py; do not edit', '#pragma once',
            '#define DM_MULTI_GAME 1', '#include "game_profile_runtime.h"']
    for key, (field, _type) in FIELDS.items():
        head.append(f'#define DM_GAME_{key} (dm_profile_current()->{field})')
    head += ['#define DM_GAME_NMOD (dm_profile_current()->nmod)',
             '#define DM_GAME_SHARED_FONT_TTF (dm_profile_current()->shared_font_ttf)',
             '#define DM_GAME_NVN_API_MAJOR (dm_profile_current()->nvn_api_major)',
             '#define DM_GAME_NVN_API_MINOR (dm_profile_current()->nvn_api_minor)', '']
    source = ['// Generated by dm/games/runtime_profiles.py; do not edit',
              '#include "game_profile_runtime.h"', '#include <ctype.h>',
              '#include <stdio.h>', '#include <stdlib.h>', '#include <string.h>',
              'static const dm_game_profile profiles[] = {']
    alphabet = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'
    if len(profiles) > len(alphabet) ** 2:
        raise ValueError('too many game profiles for two-character section namespaces')
    for index, p in enumerate(profiles):
        v = constants(p)
        nmod = int(v['NMOD'])
        versions = p.builds()
        if nmod > 8 or len(versions) > 32:
            raise ValueError(f'{p.id}: too many modules or versions')
        source.append('    {')
        source.append(f'        .embed_ns = "{alphabet[index // 36]}{alphabet[index % 36]}",')
        for key, (field, _type) in FIELDS.items():
            source.append(f'        .{field} = {v[key]},')
        source += [f'        .modules = {v["MODULES"]},',
                   f'        .nmod = {nmod},',
                   f'        .display_versions = {{{v["DISPLAY_VERSIONS"]}}},',
                   f'        .display_version_count = {sum("main" in b for b in versions.values())},',
                   f'        .shared_font_ttf = {v.get("SHARED_FONT_TTF", "-1")},',
                   f'        .nvn_api_major = {v.get("NVN_API_MAJOR", "-1")},',
                   f'        .nvn_api_minor = {v.get("NVN_API_MINOR", "-1")},',
                   '    },']
    source += ['};', 'static const dm_game_profile *selected;',
               'const dm_game_profile *dm_profile_list(size_t *count) {',
               '    if (count) *count = sizeof profiles / sizeof *profiles;',
               '    return profiles;', '}',
               'const dm_game_profile *dm_profile_find(const char *id) {',
               '    if (!id) return NULL;',
               '    for (size_t i = 0; i < sizeof profiles / sizeof *profiles; i++) {',
               '        const char *a = id, *b = profiles[i].id;',
               '        while (*a && *b && toupper((unsigned char)*a) == toupper((unsigned char)*b)) { a++; b++; }',
               '        if (!*a && !*b) return &profiles[i];',
               '    }', '    return NULL;', '}',
               'int dm_profile_select(const char *id) {',
               '    const dm_game_profile *p = dm_profile_find(id);',
               '    if (!p || (selected && selected != p)) return 0;',
               '    selected = p; return 1;', '}',
               'const dm_game_profile *dm_profile_current(void) {',
               '    if (!selected) { fputs("game profile not selected before host start\\n", stderr); abort(); }',
               '    return selected;', '}', '']
    out.mkdir(parents=True, exist_ok=True)
    (out / 'game_profile.h').write_text('\n'.join(head))
    (out / 'game_profile_runtime.c').write_text('\n'.join(source))


if __name__ == '__main__':
    if len(sys.argv) < 4:
        raise SystemExit(__doc__)
    generate(Path(sys.argv[1]), [Game(Path(path)) for path in sys.argv[2:]])
